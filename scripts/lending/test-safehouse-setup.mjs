assert.ok(page.includes('/contracts/retium_lending_safehouse.wasm'));
assert.ok(!page.includes('fetch("/contracts/retium_lending.wasm"'));
console.log('PASS WASM Blake3 pin, v0.2 metadata and setup state isolation.');

import '../tests/typescript.mjs';
import assert from 'node:assert/strict';
const {nativeBalance}=await import('../../src/lib/lending/native.ts');
const {checkedRefreshTx,validateRefreshIntent,validateSafehouseReference}=await import('../../src/lib/lending/safehouse-browser.ts');
const {SETUP_ASSET}=await import('../../src/lib/lending/setup-safehouse.ts');
assert.equal(nativeBalance({balance_rtm:'864.423264462309652564'}),'864423264462309652564');
assert.equal(nativeBalance({spendable:'0',balance_rtm:'4'}),'0');
assert.equal(nativeBalance({balance:'1000000000000000000'}),null);
assert.equal(nativeBalance({balance_rtm:'NaN'}),null);
assert.equal(nativeBalance({balance_rtm:'0.4405'}),'440500000000000000');
const s={safehouse:'rete_safehouse',rusd_contract_id:SETUP_ASSET,rusd_deployed:true,total_supply_atomic:'1000000000000000000000000000',inventory_atomic:'999999999000000000000000000',locked_atomic:'1000000000000000000',released_atomic:'1000000000000000000',burned_atomic:'0'};
assert.equal(validateSafehouseReference(s),'1000000000000000000');
assert.throws(()=>validateSafehouseReference({...s,rusd_contract_id:'wrong'}));
assert.throws(()=>validateSafehouseReference({...s,locked_atomic:'0'}));
const p={wallet:'rete'+'a'.repeat(68),market:'b'.repeat(64),nonce:5,observed:'1792572808326',until:1792572853326,txId:'tx_'+'c'.repeat(32)};
validateRefreshIntent(p,p.wallet,p.market);
const tx={tx_id:p.txId,sender:p.wallet,recipient:p.market,nonce:5,action:'call',amount:'0',call:{contract:p.market,method:'refresh_price'},finality:'HardFinal',exec_status:'ok'};
assert.equal(checkedRefreshTx(tx,p),'confirmed');
assert.equal(checkedRefreshTx({...tx,exec_status:null},p),'pending');
assert.equal(checkedRefreshTx({...tx,exec_error:'reverted'},p),'failed');
for(const change of [{nonce:4},{sender:'wrong'},{recipient:'wrong'},{call:{contract:p.market,method:'approve'}},{amount:'1'}])assert.throws(()=>checkedRefreshTx({...tx,...change},p));
assert.throws(()=>checkedRefreshTx({...tx,call:{...tx.call,args:['wrong']}},p));
console.log('PASS exact RTM balances, missing/zero distinction, Safehouse identity/reserves, and oracle TX identity/execution checks.');
